# addition of 3 numbers and finding of 3 numbers
a = int(input("Enter first number: "))
b = int(input("Enter second number: "))
c = int(input("Enter third number: "))

# sum
sum = a+b+c
# print sum
print(f"Sum of {a} + {b} + {c} is: ", sum)

# avg
avg = sum/3
# print avg
print(f"Average of {a},{b},{c} is: ", avg)


